import { fireEvent, render, screen } from '@testing-library/react'
import { describe, expect, it, vi } from 'vitest'
import DeductionReview from '../../src/screens/DeductionReview'

const updateLaunchEntryMock = vi.fn()

vi.mock('../../src/components/ScreenContainer', () => ({
  default: ({ title, children }: { title: string; children: React.ReactNode }) => (
    <section>
      <h1>{title}</h1>
      {children}
    </section>
  ),
}))

vi.mock('../../src/screens/financialOverview', () => ({
  getMonthContext: () => ({
    companyId: 'cmp-ui',
    companyName: 'Empresa UI',
    month: '2026-05',
  }),
  formatCurrency: (value: number) => `R$ ${value.toFixed(2)}`,
}))

vi.mock('../../src/launchStore', () => ({
  listLaunchEntries: () => [
    {
      id: 'est-01',
      companyId: 'cmp-ui',
      month: '2026-05',
      costType: 'company',
      dreGroup: 'deductions',
      categoryId: 'cat-company-deduction-taxes-sales',
      categoryName: 'Tributos sobre vendas',
      description: 'Dedução prevista sobre receita: Serviço A',
      amount: 80,
      createdAt: '2026-05-25T10:00:00.000Z',
      sourceType: 'tax_estimation',
      autoGenerated: true,
      reviewStatus: 'suggested',
      linkedEntryId: 'rev-01',
      estimationSnapshot: {
        annualRevenueForecastUsed: 200000,
        matchedBracketId: 'ded-bracket-02',
        matchedRate: 8,
        formulaVersion: 'estimated-generic-v1',
        calculatedAt: '2026-05-25T10:00:00.000Z',
      },
    },
  ],
  getLaunchEntryById: (entryId: string) =>
    entryId === 'rev-01'
      ? {
          id: 'rev-01',
          description: 'Serviço A',
        }
      : null,
  updateLaunchEntry: (...args: unknown[]) => updateLaunchEntryMock(...args),
}))

describe('DeductionReview UI', () => {
  it('aprova item sugerido', () => {
    render(<DeductionReview />)

    fireEvent.click(screen.getByRole('button', { name: 'Aprovar' }))

    expect(updateLaunchEntryMock).toHaveBeenCalledWith('est-01', { reviewStatus: 'approved' })
  })

  it('edita valor e marca como editado', () => {
    render(<DeductionReview />)

    fireEvent.click(screen.getByRole('button', { name: 'Editar' }))
    const input = screen.getByLabelText('Valor da dedução')
    fireEvent.change(input, { target: { value: '20000' } })
    fireEvent.click(screen.getByRole('button', { name: 'Salvar' }))

    expect(updateLaunchEntryMock).toHaveBeenCalledWith('est-01', {
      amount: 200,
      reviewStatus: 'edited',
    })
  })
})
