import type { DreGroup } from './categoryStore'
import { getCategoryById, listCategories } from './categoryStore'
import { listDeductionBrackets } from './deductionBracketStore'
import {
  calculateEstimatedDeduction,
  DEFAULT_DEDUCTION_FORMULA_VERSION,
  type DeductionEstimationSnapshot,
} from './deductionEstimation'
import { monthLifecycleStore } from './monthLifecycle'
import { getTaxProfile } from './taxProfileStore'

const STORAGE_KEY = 'empresa-facil:launch-entries:v1'
const TAX_ESTIMATION_SOURCE_TYPE = 'tax_estimation'
const DEFAULT_SOURCE_TYPE = 'manual'
const DEDUCTION_FORMULA_VERSION = DEFAULT_DEDUCTION_FORMULA_VERSION

export type EntrySourceType = 'manual' | 'tax_estimation' | 'bank_import'
export type EntryReviewStatus = 'suggested' | 'approved' | 'rejected' | 'edited'
export type AccountOrigin = 'company' | 'personal' | 'unknown'

export type EstimationSnapshot = DeductionEstimationSnapshot

export interface StoredLaunchEntry {
  id: string
  companyId: string
  month: string
  costType: 'company' | 'personal'
  accountOrigin: AccountOrigin
  dreGroup: DreGroup
  categoryId: string
  categoryName: string
  description: string
  amount: number
  createdAt: string
  sourceType?: EntrySourceType
  autoGenerated?: boolean
  reviewStatus?: EntryReviewStatus
  linkedEntryId?: string
  estimationSnapshot?: EstimationSnapshot
  flaggedForReview?: boolean
  reconciliationStatus?: 'not_applicable' | 'pending' | 'confirmed_internal_transfer'
  reconciliationReason?: string
}

function hasLocalStorage() {
  return typeof window !== 'undefined' && typeof window.localStorage !== 'undefined'
}

function readEntries(): StoredLaunchEntry[] {
  if (!hasLocalStorage()) {
    return []
  }

  const raw = window.localStorage.getItem(STORAGE_KEY)
  if (!raw) {
    return []
  }

  try {
    const parsed = JSON.parse(raw)
    if (!Array.isArray(parsed)) {
      return []
    }

    return parsed.map((entry) => normalizeEntry(entry)).filter(Boolean) as StoredLaunchEntry[]
  } catch {
    return []
  }
}

function normalizeEntry(entry: unknown): StoredLaunchEntry | null {
  if (!entry || typeof entry !== 'object') {
    return null
  }

  const input = entry as Partial<StoredLaunchEntry>
  if (!input.id || !input.companyId || !input.month || !input.costType || !input.description) {
    return null
  }

  let estimationSnapshot: EstimationSnapshot | undefined
  if (input.estimationSnapshot && typeof input.estimationSnapshot === 'object') {
    const snapshot = input.estimationSnapshot as Partial<EstimationSnapshot>
    const annualRevenueForecastUsed = Number(snapshot.annualRevenueForecastUsed)
    const matchedRate = Number(snapshot.matchedRate)

    if (
      Number.isFinite(annualRevenueForecastUsed) &&
      Number.isFinite(matchedRate) &&
      typeof snapshot.matchedBracketId === 'string' &&
      snapshot.matchedBracketId.trim() &&
      typeof snapshot.formulaVersion === 'string' &&
      snapshot.formulaVersion.trim()
    ) {
      estimationSnapshot = {
        annualRevenueForecastUsed,
        matchedBracketId: snapshot.matchedBracketId.trim(),
        matchedRate,
        formulaVersion: snapshot.formulaVersion.trim(),
        calculatedAt:
          typeof snapshot.calculatedAt === 'string' && snapshot.calculatedAt.trim()
            ? snapshot.calculatedAt
            : new Date().toISOString(),
      }
    }
  }

  return {
    id: String(input.id),
    companyId: String(input.companyId),
    month: String(input.month),
    costType: input.costType === 'personal' ? 'personal' : 'company',
    accountOrigin:
      input.accountOrigin === 'company' || input.accountOrigin === 'personal'
        ? input.accountOrigin
        : 'unknown',
    dreGroup:
      input.dreGroup === 'revenue' || input.dreGroup === 'deductions' ? input.dreGroup : 'expenses',
    categoryId: input.categoryId ? String(input.categoryId) : 'uncategorized',
    categoryName: input.categoryName ? String(input.categoryName) : 'Sem categoria',
    description: String(input.description),
    amount: Number(input.amount) || 0,
    createdAt: input.createdAt ? String(input.createdAt) : new Date().toISOString(),
    sourceType:
      input.sourceType === TAX_ESTIMATION_SOURCE_TYPE || input.sourceType === 'bank_import'
        ? input.sourceType
        : DEFAULT_SOURCE_TYPE,
    autoGenerated: Boolean(input.autoGenerated),
    reviewStatus:
      input.reviewStatus === 'suggested' ||
      input.reviewStatus === 'approved' ||
      input.reviewStatus === 'rejected' ||
      input.reviewStatus === 'edited'
        ? input.reviewStatus
        : 'approved',
    linkedEntryId: typeof input.linkedEntryId === 'string' && input.linkedEntryId.trim() ? input.linkedEntryId : undefined,
    estimationSnapshot,
    flaggedForReview: Boolean(input.flaggedForReview),
    reconciliationStatus:
      input.reconciliationStatus === 'pending' || input.reconciliationStatus === 'confirmed_internal_transfer'
        ? input.reconciliationStatus
        : 'not_applicable',
    reconciliationReason:
      typeof input.reconciliationReason === 'string' && input.reconciliationReason.trim()
        ? input.reconciliationReason.trim()
        : undefined,
  }
}

function isCompanyRevenue(entry: StoredLaunchEntry) {
  return entry.costType === 'company' && entry.dreGroup === 'revenue'
}

function getTaxDeductionCategory() {
  const preferred = getCategoryById('cat-company-deduction-taxes-sales')
  if (preferred) {
    return preferred
  }

  return (
    listCategories({ costType: 'company', dreGroup: 'deductions' })[0] ?? {
      id: 'uncategorized-deduction',
      name: 'Deduções previstas',
    }
  )
}

function removeLinkedEstimationEntries(entries: StoredLaunchEntry[], linkedEntryId: string) {
  return entries.filter(
    (entry) => !(entry.sourceType === TAX_ESTIMATION_SOURCE_TYPE && entry.linkedEntryId === linkedEntryId)
  )
}

function upsertLinkedEstimationEntry(entries: StoredLaunchEntry[], revenueEntry: StoredLaunchEntry) {
  const profile = getTaxProfile(revenueEntry.companyId)
  if (!profile) {
    return removeLinkedEstimationEntries(entries, revenueEntry.id)
  }

  if (monthLifecycleStore.isMonthClosed({ companyId: revenueEntry.companyId, month: revenueEntry.month })) {
    return removeLinkedEstimationEntries(entries, revenueEntry.id)
  }

  const estimation = calculateEstimatedDeduction({
    revenueAmount: revenueEntry.amount,
    annualRevenueForecast: profile.annualRevenueForecast,
    brackets: listDeductionBrackets(),
    formulaVersion: DEDUCTION_FORMULA_VERSION,
  })
  if (!estimation) {
    return removeLinkedEstimationEntries(entries, revenueEntry.id)
  }

  const category = getTaxDeductionCategory()
  const calculatedAt = new Date().toISOString()
  const estimationEntryId = `tax-est-${revenueEntry.id}`

  const estimationEntry: StoredLaunchEntry = {
    id: estimationEntryId,
    companyId: revenueEntry.companyId,
    month: revenueEntry.month,
    costType: 'company',
    accountOrigin: 'unknown',
    dreGroup: 'deductions',
    categoryId: category.id,
    categoryName: category.name,
    description: `Dedução prevista sobre receita: ${revenueEntry.description}`,
    amount: estimation.estimatedAmount,
    createdAt: calculatedAt,
    sourceType: TAX_ESTIMATION_SOURCE_TYPE,
    autoGenerated: true,
    reviewStatus: 'suggested',
    linkedEntryId: revenueEntry.id,
    estimationSnapshot: { ...estimation.snapshot, calculatedAt },
  }

  const next = removeLinkedEstimationEntries(entries, revenueEntry.id)
  return [...next, estimationEntry]
}

function applyAutoEstimation(entries: StoredLaunchEntry[], targetEntry: StoredLaunchEntry | null) {
  if (!targetEntry) {
    return entries
  }

  if (targetEntry.sourceType === TAX_ESTIMATION_SOURCE_TYPE) {
    return entries
  }

  if (!isCompanyRevenue(targetEntry)) {
    return removeLinkedEstimationEntries(entries, targetEntry.id)
  }

  return upsertLinkedEstimationEntry(entries, targetEntry)
}

function writeEntries(entries: StoredLaunchEntry[]) {
  if (!hasLocalStorage()) {
    return
  }

  window.localStorage.setItem(STORAGE_KEY, JSON.stringify(entries))
}

export function saveLaunchEntry(entry: StoredLaunchEntry) {
  const nextEntry = normalizeEntry(entry)
  if (!nextEntry) {
    throw new Error('Falha ao salvar lançamento: payload inválido.')
  }

  const current = readEntries()
  const next = applyAutoEstimation([...current, nextEntry], nextEntry)
  writeEntries(next)
}

export function getLaunchEntryById(entryId: string) {
  return readEntries().find((entry) => entry.id === entryId) ?? null
}

export function updateLaunchEntry(entryId: string, update: Partial<StoredLaunchEntry>) {
  const current = readEntries()
  const index = current.findIndex((entry) => entry.id === entryId)
  if (index === -1) {
    throw new Error('Lançamento não encontrado.')
  }

  const nextEntry = normalizeEntry({
    ...current[index],
    ...update,
    id: current[index].id,
    companyId: current[index].companyId,
    month: current[index].month,
    createdAt: current[index].createdAt,
  })

  if (!nextEntry) {
    throw new Error('Falha ao atualizar lançamento.')
  }

  const next = [...current]
  next[index] = nextEntry
  const withEstimation = applyAutoEstimation(next, nextEntry)
  writeEntries(withEstimation)
  return nextEntry
}

export function removeLaunchEntry(entryId: string) {
  const current = readEntries()
  const entryToRemove = current.find((entry) => entry.id === entryId) ?? null
  let next = current.filter((entry) => entry.id !== entryId)

  if (entryToRemove && isCompanyRevenue(entryToRemove)) {
    next = removeLinkedEstimationEntries(next, entryToRemove.id)
  }

  writeEntries(next)
}

interface ListLaunchEntriesFilters {
  companyId?: string
  month?: string
  costType?: 'company' | 'personal' | 'all'
  dreGroup?: DreGroup | 'all'
  categoryId?: string
  search?: string
  flaggedForReview?: boolean
}

export function listLaunchEntries(filters: ListLaunchEntriesFilters = {}) {
  const { companyId, month, costType = 'all', dreGroup = 'all', categoryId, search, flaggedForReview } = filters
  const searchLower = search?.trim().toLowerCase()

  return readEntries()
    .filter((entry) => {
      if (companyId && entry.companyId !== companyId) {
        return false
      }

      if (month && entry.month !== month) {
        return false
      }

      if (costType !== 'all' && entry.costType !== costType) {
        return false
      }

      if (dreGroup !== 'all' && entry.dreGroup !== dreGroup) {
        return false
      }

      if (categoryId && entry.categoryId !== categoryId) {
        return false
      }

      if (searchLower && !entry.description.toLowerCase().includes(searchLower)) {
        return false
      }

      if (flaggedForReview === true && !entry.flaggedForReview) {
        return false
      }

      return true
    })
    .sort((left, right) => right.createdAt.localeCompare(left.createdAt))
}

export function toggleReviewFlag(entryId: string) {
  const current = readEntries()
  const index = current.findIndex((entry) => entry.id === entryId)
  if (index === -1) return

  const next = [...current]
  next[index] = { ...next[index], flaggedForReview: !next[index].flaggedForReview }
  writeEntries(next)
}

export function listLaunchLines({
  companyId,
  month,
  costType = 'all',
}: {
  companyId: string
  month: string
  costType?: 'company' | 'personal' | 'all'
}): DreLineInput[] {
  return listLaunchEntries({ companyId, month, costType })
    .filter((entry) => entry.reviewStatus !== 'rejected')
    .map((entry) =>
      createDreLineInput({
        entryId: entry.id,
        companyId: entry.companyId,
        month: entry.month,
        amount: entry.amount,
        dreGroup: entry.dreGroup,
        description: entry.description,
      })
    )
}

export function recomputeAutomaticDeductions(filters: { companyId?: string } = {}) {
  const { companyId } = filters
  const current = readEntries()

  const scopedEntries = companyId
    ? current.filter((entry) => entry.companyId === companyId)
    : current

  const keepEntries = current.filter((entry) => {
    if (entry.sourceType !== TAX_ESTIMATION_SOURCE_TYPE) {
      return true
    }

    if (!companyId) {
      return false
    }

    return entry.companyId !== companyId
  })

  const revenues = scopedEntries.filter(
    (entry) => entry.sourceType !== TAX_ESTIMATION_SOURCE_TYPE && isCompanyRevenue(entry)
  )

  let next = keepEntries
  for (const revenueEntry of revenues) {
    next = applyAutoEstimation(next, revenueEntry)
  }

  writeEntries(next)
}
